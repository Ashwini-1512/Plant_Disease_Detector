def make_class_template_bgr(disease_class, size=224):
    """Fallback only - used exclusively for a class with zero real photos found.
    Uses hashlib (not Python's built-in hash()) so the seed - and therefore the
    image - is identical every run and every machine."""
    seed = int(hashlib.md5(disease_class.encode()).hexdigest(), 16) % (2 ** 32 - 1)
    rng = np.random.default_rng(seed)
    base_color = rng.integers(30, 220, size=3)
    noise = rng.integers(-25, 25, size=(size, size, 3))
    arr_rgb = np.clip(base_color + noise, 0, 255).astype(np.uint8)
    return cv2.cvtColor(arr_rgb, cv2.COLOR_RGB2BGR)


