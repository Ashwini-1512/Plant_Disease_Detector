def find_base_model_and_head(model):
    base_model = None
    head_layers = []
    for layer in model.layers:
        if isinstance(layer, tf.keras.Model):
            base_model = layer
            continue
        if base_model is not None:
            head_layers.append(layer)
    if base_model is None:
        raise ValueError("Could not find the nested base architecture inside this model")
    return base_model, head_layers

def grad_cam(model, img_array, class_index=None):
    base_model, head_layers = find_base_model_and_head(model)
    conv_feature_model = tf.keras.Model(base_model.input, base_model.output)
    classifier_input = tf.keras.Input(shape=base_model.output.shape[1:])
    x = classifier_input
    for layer in head_layers:
        if isinstance(layer, (tf.keras.layers.Dropout, tf.keras.layers.BatchNormalization)):
            x = layer(x, training=False)
        else:
            x = layer(x)
    classifier_model = tf.keras.Model(classifier_input, x)
    with tf.GradientTape() as tape:
        conv_output = conv_feature_model(img_array)
        tape.watch(conv_output)
        predictions = classifier_model(conv_output)
        if class_index is None:
            class_index = tf.argmax(predictions[0])
        loss = predictions[:, class_index]
    grads = tape.gradient(loss, conv_output)
    pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))
    conv_output = conv_output[0]
    heatmap = tf.reduce_sum(tf.multiply(pooled_grads, conv_output), axis=-1)
    heatmap = tf.maximum(heatmap, 0) / (tf.math.reduce_max(heatmap) + 1e-8)
    return heatmap.numpy(), int(class_index)

def overlay_heatmap(img_rgb_uint8, heatmap, alpha=0.4):
    heatmap = cv2.resize(heatmap, (img_rgb_uint8.shape[1], img_rgb_uint8.shape[0]))
    heatmap = np.uint8(255 * heatmap)
    heatmap_color = cv2.applyColorMap(heatmap, cv2.COLORMAP_JET)
    heatmap_color = cv2.cvtColor(heatmap_color, cv2.COLOR_BGR2RGB)
    return np.uint8(img_rgb_uint8 * (1 - alpha) + heatmap_color * alpha)

def decode_image(file_storage):
    data = np.frombuffer(file_storage.read(), np.uint8)
    img_bgr = cv2.imdecode(data, cv2.IMREAD_COLOR)
    return cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)

def prep_for_model(img_rgb_uint8):
    """Returns (model_input, display_image). model_input keeps raw [0,255] pixels
    (EfficientNet-correct) run through efficientnet_preprocess (a documented
    no-op); display_image stays plain uint8 [0,255] for showing in the browser."""
    resized = cv2.resize(img_rgb_uint8, IMG_SIZE)
    model_input = efficientnet_preprocess(resized.astype(np.float32))
    return np.expand_dims(model_input, axis=0), resized

def encode_png_b64(img_rgb_uint8):
    img_bgr = cv2.cvtColor(img_rgb_uint8, cv2.COLOR_RGB2BGR)
    ok, buf = cv2.imencode(".png", img_bgr)
    return base64.b64encode(buf.tobytes()).decode("utf-8")


