def compute_sus_score(responses):
    assert len(responses) == 10, "SUS requires exactly 10 responses"
    total = 0
    for i, r in enumerate(responses):
        pos = (i % 2 == 0)
        total += (r - 1) if pos else (5 - r)
    return total * 2.5


