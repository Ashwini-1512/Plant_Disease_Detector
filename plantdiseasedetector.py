def build_real_images_by_class(search_root, class_names):
    """Recursively scan the downloaded dataset and, for every folder whose name
    exactly matches one of this project's disease_class names, collect every
    image file inside it. Real datasets ship several near-duplicate folder
    trees (color/grayscale/segmented) - all matching folders are pooled."""
    by_class = {c: [] for c in class_names}
    if not (search_root and os.path.isdir(search_root)):
        return by_class
    class_set = set(class_names)
    for dirpath, dirnames, filenames in os.walk(search_root):
        folder_name = os.path.basename(dirpath)
        if folder_name in class_set:
            imgs = [os.path.join(dirpath, f) for f in filenames
                    if f.lower().endswith((".jpg", ".jpeg", ".png"))]
            by_class[folder_name].extend(imgs)
    return by_class


